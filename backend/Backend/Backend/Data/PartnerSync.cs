using Backend.Models;
using Microsoft.EntityFrameworkCore;

namespace Backend.Data;

/// <summary>
/// Creates the partner tables on databases that already exist (EnsureCreated only handles brand new
/// ones) and adds the known partners, in ONE transaction at startup.
/// It only adds what is missing and never overwrites or deletes, so edits made directly in the
/// database survive a restart. To remove a partner or link for good, delete it here as well as in the database.
/// </summary>
public static class PartnerSync
{
    private const string Faculty = "Facultatea de Matematică și Informatică, UNITBV";

    // Type, IsFeatured and DisplayOrder are for the partners page and footer.
    // A null Type means: only credited on its events, not a partner of ASIMBv itself.
    private sealed record PartnerSeed(
        string Name,
        string? LogoUrl,
        string? WebsiteUrl,
        string? Type = null,
        bool IsFeatured = false,
        int DisplayOrder = 0);

    private static readonly PartnerSeed[] Partners =
    [
        new(Faculty, "/parteneri/fmi-unitbv.png", "https://mateinfo.unitbv.ro", PartnerTypes.Educational, IsFeatured: true, DisplayOrder: 1),
        new("Uniunea Studenților din România", "/parteneri/uni.png", "https://uniunea-studentilor.ro", PartnerTypes.Affiliation, IsFeatured: true, DisplayOrder: 2),
        new("BEST Brașov", "/parteneri/best-brasov.png", "https://bestbrasov.ro", PartnerTypes.Association, IsFeatured: true, DisplayOrder: 3),
        new("ASSM", "/parteneri/assm.png", "https://assmbv.org", PartnerTypes.Association, IsFeatured: true, DisplayOrder: 4),

        new("Arvato Systems", "/parteneri/arvato-systems.svg", "https://www.arvato-systems.com"),
        new("CANAM", "/parteneri/canam.png", "https://www.canam.com"),
        new("Enovation", "/parteneri/enovation.png", null),
        new("Eviden", "/parteneri/eviden.png", "https://eviden.com"),
        new("principal33", "/parteneri/principal33.png", "https://www.principal33.com"),
        new("Rebel Dot", "/parteneri/rebel-dot.svg", "https://www.rebeldot.com"),
        new("Siemens", "/parteneri/siemens.svg", "https://www.siemens.com"),
        new("Trimble", "/parteneri/trimble.svg", "https://www.trimble.com"),
